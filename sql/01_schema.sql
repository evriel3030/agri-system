-- =====================================================================
-- Agriculture Information System - 01_schema.sql
-- Run this FIRST in the Supabase SQL Editor.
-- Creates: lookup tables, main tables, constraints, triggers, security.
-- Safe to re-run: it drops the old tables first (DELETES ALL DATA!).
-- =====================================================================

DROP TABLE IF EXISTS harvest, planting, farm, crop, crop_type, farmer, app_user, role,
    harvest_remark, quality_grade, planting_status, season, crop_category,
    irrigation_type, soil_type CASCADE;
DROP FUNCTION IF EXISTS set_updated_at() CASCADE;
DROP FUNCTION IF EXISTS check_harvest_date() CASCADE;

-- ---------------------------------------------------------------------
-- 1. LOOKUP (REFERENCE) TABLES
--    The user sees the description in a dropdown; the main tables store
--    only the numeric ID (a foreign key).
-- ---------------------------------------------------------------------
CREATE TABLE soil_type (
    soil_type_id   SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soil_type_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE irrigation_type (
    irrigation_type_id   SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    irrigation_type_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE crop_category (
    category_id   SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE season (
    season_id   SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_name VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE planting_status (
    status_id   SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE quality_grade (
    quality_grade_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_name       VARCHAR(30) NOT NULL UNIQUE
);

-- Exactly as shown in the project document (remark_id / remark_description)
CREATE TABLE harvest_remark (
    remark_id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remark_description VARCHAR(100) NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------
-- 2. USERS AND ROLES (authentication / access control)
-- ---------------------------------------------------------------------
CREATE TABLE role (
    role_id   SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE app_user (
    user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,            -- bcrypt hash, never plain text
    full_name     VARCHAR(100) NOT NULL,
    role_id       SMALLINT     NOT NULL REFERENCES role(role_id) ON DELETE RESTRICT,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_username_len CHECK (char_length(username) >= 3)
);

-- ---------------------------------------------------------------------
-- 3. MAIN TABLES
-- ---------------------------------------------------------------------
CREATE TABLE farmer (
    farmer_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR(50)  NOT NULL,
    last_name       VARCHAR(50)  NOT NULL,
    contact_number  VARCHAR(20)  NOT NULL UNIQUE,
    address         VARCHAR(150) NOT NULL,
    date_registered DATE         NOT NULL DEFAULT CURRENT_DATE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    updated_by      INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_farmer_contact CHECK (contact_number ~ '^(09[0-9]{9}|\+639[0-9]{9})$')
);

CREATE TABLE farm (
    farm_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id          INTEGER      NOT NULL REFERENCES farmer(farmer_id) ON DELETE RESTRICT,
    farm_name          VARCHAR(100) NOT NULL,
    location           VARCHAR(150) NOT NULL,
    area_hectares      NUMERIC(8,2) NOT NULL,
    soil_type_id       SMALLINT     NOT NULL REFERENCES soil_type(soil_type_id) ON DELETE RESTRICT,
    irrigation_type_id SMALLINT     NOT NULL REFERENCES irrigation_type(irrigation_type_id) ON DELETE RESTRICT,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by         INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    updated_by         INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_farm_area CHECK (area_hectares > 0),
    CONSTRAINT uq_farm_per_farmer UNIQUE (farmer_id, farm_name)
);

CREATE TABLE crop_type (
    crop_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_name    VARCHAR(80) NOT NULL UNIQUE,
    category_id  SMALLINT    NOT NULL REFERENCES crop_category(category_id) ON DELETE RESTRICT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by   INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    updated_by   INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL
);

CREATE TABLE crop (
    crop_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_type_id       INTEGER     NOT NULL REFERENCES crop_type(crop_type_id) ON DELETE RESTRICT,
    variety            VARCHAR(80) NOT NULL,
    growing_period_days INTEGER    NOT NULL,
    season_id          SMALLINT    NOT NULL REFERENCES season(season_id) ON DELETE RESTRICT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by         INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    updated_by         INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_crop_days CHECK (growing_period_days BETWEEN 1 AND 1000),
    CONSTRAINT uq_crop_variety UNIQUE (crop_type_id, variety)
);

CREATE TABLE planting (
    planting_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id               INTEGER      NOT NULL REFERENCES farm(farm_id) ON DELETE RESTRICT,
    crop_id               INTEGER      NOT NULL REFERENCES crop(crop_id) ON DELETE RESTRICT,
    planting_date         DATE         NOT NULL,
    area_planted          NUMERIC(8,2) NOT NULL,
    seed_quantity         NUMERIC(8,2) NOT NULL,
    expected_harvest_date DATE         NOT NULL,
    status_id             SMALLINT     NOT NULL REFERENCES planting_status(status_id) ON DELETE RESTRICT,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by            INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    updated_by            INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_planting_area  CHECK (area_planted > 0),
    CONSTRAINT chk_planting_seed  CHECK (seed_quantity > 0),
    CONSTRAINT chk_planting_dates CHECK (expected_harvest_date >= planting_date)
);

CREATE TABLE harvest (
    harvest_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planting_id         INTEGER       NOT NULL REFERENCES planting(planting_id) ON DELETE RESTRICT,
    harvest_date        DATE          NOT NULL,
    quantity_kg         NUMERIC(10,2) NOT NULL,
    selling_price_per_kg NUMERIC(10,2) NOT NULL,
    quality_grade_id    SMALLINT      NOT NULL REFERENCES quality_grade(quality_grade_id) ON DELETE RESTRICT,
    remark_id           SMALLINT      NOT NULL REFERENCES harvest_remark(remark_id) ON DELETE RESTRICT,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by          INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    updated_by          INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_harvest_qty   CHECK (quantity_kg > 0),
    CONSTRAINT chk_harvest_price CHECK (selling_price_per_kg >= 0)
);

-- Indexes on foreign keys (faster JOINs, filters and delete checks)
CREATE INDEX idx_farm_farmer      ON farm(farmer_id);
CREATE INDEX idx_crop_type_category ON crop_type(category_id);
CREATE INDEX idx_crop_type        ON crop(crop_type_id);
CREATE INDEX idx_planting_farm    ON planting(farm_id);
CREATE INDEX idx_planting_crop    ON planting(crop_id);
CREATE INDEX idx_planting_status  ON planting(status_id);
CREATE INDEX idx_harvest_planting ON harvest(planting_id);
CREATE INDEX idx_harvest_date     ON harvest(harvest_date);

-- ---------------------------------------------------------------------
-- 4. TRIGGERS
-- ---------------------------------------------------------------------
-- 4a. Keep updated_at current on every UPDATE
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_farmer_upd   BEFORE UPDATE ON farmer   FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_farm_upd     BEFORE UPDATE ON farm     FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_crop_type_upd BEFORE UPDATE ON crop_type FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_crop_upd     BEFORE UPDATE ON crop     FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_planting_upd BEFORE UPDATE ON planting FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_harvest_upd  BEFORE UPDATE ON harvest  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_user_upd     BEFORE UPDATE ON app_user FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 4b. A harvest cannot happen before the crop was planted
--     (a CHECK constraint cannot look at another table, so we use a trigger)
CREATE FUNCTION check_harvest_date() RETURNS trigger AS $$
DECLARE
    p_date DATE;
BEGIN
    SELECT planting_date INTO p_date FROM planting WHERE planting_id = NEW.planting_id;
    IF NEW.harvest_date < p_date THEN
        RAISE EXCEPTION 'Harvest date cannot be earlier than the planting date (%).', p_date
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_harvest_date BEFORE INSERT OR UPDATE ON harvest
    FOR EACH ROW EXECUTE FUNCTION check_harvest_date();

-- ---------------------------------------------------------------------
-- 5. SECURITY (Supabase)
--    Turning on Row Level Security with NO policies blocks Supabase's
--    public REST API (anon key) from reading these tables.
--    The PHP app connects with the database owner account, which is
--    not affected, so the app keeps working normally.
-- ---------------------------------------------------------------------
DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['soil_type','irrigation_type','crop_category','season',
        'planting_status','quality_grade','harvest_remark','role','app_user',
        'farmer','farm','crop_type','crop','planting','harvest']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    END LOOP;
END $$;
